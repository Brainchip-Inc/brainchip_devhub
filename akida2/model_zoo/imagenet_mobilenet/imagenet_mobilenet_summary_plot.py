"""Summary scatter plot for the README: accuracy against latency.

Akida top-1 accuracy against the latency projected to the AKD2500 target clock,
for every model that maps onto the 6-node Akida 2 FPGA. The models that need a
larger device have no hardware numbers and are left out.

We deliberately use points here, not lines: a few widely spaced widths per
version are far too few to justify joining, and a line would suggest a smooth
trade-off that was never measured.

Each model is plotted at its fastest mapping mode, with the same rule as the
Akida 2 landing page: the simplest mode within 1% of the fewest cycles.
Everything is read from ``docs/metrics.json``, so this stays in step with the
tables it sits above: it is regenerated by ``update_readme.py``.

Example
-------
    python imagenet_mobilenet_summary_plot.py
"""
import json
import pathlib

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

# Mapping modes, simplest first, and the tie tolerance used to pick the fastest
# (as in akida2/update_readme.py).
MAP_MODES = {'minimal': 'Minimal', 'allnps': 'AllNPs', 'hwpr': 'HwPr'}
TIE_TOLERANCE = 0.01

# Series are the two MobileNet versions, in fixed order, identified by both
# colour and marker shape. Only the widths that map onto the FPGA are listed.
SERIES = [
    {'prefix': 'v1', 'alphas': [0.25, 0.5, 0.75], 'color': '#2a78d6', 'marker': 'o',
     'label': 'MobileNetV1'},
    {'prefix': 'v2', 'alphas': [0.35, 0.5], 'color': '#eb6834', 'marker': 's',
     'label': 'MobileNetV2'},
]

SURFACE = '#fcfcfb'
INK = '#0b0b0b'
INK_MUTED = '#52514e'
GRID = '#dcdcd8'


def _prefix(version, alpha):
    """Metrics key prefix for one model. Mirrors model.metrics_prefix()."""
    return f'{version}_a{round(alpha * 100)}_'


def _value(metrics, key):
    """Read a metrics value as a float, tolerating the trailing '%' on accuracies."""
    return float(metrics[key].rstrip('%').replace(',', ''))


def fastest_mode(metrics, prefix):
    """Simplest mapping mode within TIE_TOLERANCE of the fewest cycles."""
    cycles = {m: _value(metrics, f'{prefix}{m}_cycles') for m in MAP_MODES
              if f'{prefix}{m}_cycles' in metrics}
    fastest = min(cycles.values())
    return next(m for m in MAP_MODES if m in cycles and cycles[m] <= fastest * (1 + TIE_TOLERANCE))


def plot_summary(metrics, savepath=None):
    """Plot Akida top-1 accuracy against projected latency, for every FPGA model.

    Args:
        metrics:  parsed docs/metrics.json.
        savepath: if given, save the figure to this path (PNG).

    Returns:
        matplotlib Figure.
    """
    fig, ax = plt.subplots(figsize=(7.5, 4.8), constrained_layout=True)
    fig.patch.set_facecolor(SURFACE)
    ax.set_facecolor(SURFACE)

    x_max = 0.0
    for series in SERIES:
        xs, ys, modes = [], [], []
        for alpha in series['alphas']:
            prefix = _prefix(series['prefix'], alpha)
            mode = fastest_mode(metrics, prefix)
            xs.append(_value(metrics, f'{prefix}{mode}_projected_ms'))
            ys.append(_value(metrics, f'{prefix}akida_t1'))
            modes.append(MAP_MODES[mode])
        x_max = max(x_max, max(xs))

        ax.plot(xs, ys, color=series['color'], marker=series['marker'],
                markersize=10, linestyle='none', markeredgecolor=SURFACE,
                markeredgewidth=1.5, label=series['label'], zorder=3)

        # Direct-label each point with its width multiplier and mapping mode
        for alpha, mode, x, y in zip(series['alphas'], modes, xs, ys):
            ax.annotate(f'alpha {alpha} ({mode})', (x, y), textcoords='offset points',
                        xytext=(8, -4), ha='left', fontsize=10, color=INK_MUTED, zorder=4)

    ax.set_xlabel('Projected latency on AKD2500 at 1 GHz (ms per inference)',
                  fontsize=12, color=INK)
    ax.set_ylabel('Akida top-1 accuracy (%)', fontsize=12, color=INK)
    ax.set_xlim(0, 1.35 * x_max)
    ax.grid(True, color=GRID, linewidth=0.8, zorder=0)
    ax.set_axisbelow(True)
    ax.tick_params(labelsize=11, colors=INK_MUTED)
    for side in ('top', 'right'):
        ax.spines[side].set_visible(False)
    for side in ('left', 'bottom'):
        ax.spines[side].set_color(GRID)
    ax.legend(loc='lower right', fontsize=11, frameon=True,
              facecolor=SURFACE, edgecolor=GRID, labelcolor=INK)
    ax.set_title('MobileNet on ImageNet: accuracy against latency\n'
                 '(8-bit, measured on the Akida 2 FPGA, fastest mapping)',
                 fontsize=13, fontweight='bold', color=INK)

    if savepath is not None:
        fig.savefig(savepath, dpi=150, facecolor=SURFACE)

    return fig


if __name__ == '__main__':
    here = pathlib.Path(__file__).parent
    metrics = json.loads((here / 'docs' / 'metrics.json').read_text())
    out = here / 'docs' / 'ref_benchmark_summary.png'
    plot_summary(metrics, savepath=out)
    print(f'Summary plot written to {out}')
